PUBLIC_KEY = b"sigil-public-v1"   # shared detection key so any verifier can find Sigil marks

LABELS = {
    "en": "AI-generated", "de": "KI-generiert", "fr": "Généré par IA", "es": "Generado por IA",
    "it": "Generato con IA", "ko": "AI 생성", "hi": "एआई-जनित", "ja": "AI生成",
}
TEXT_DISCLOSURES = {
    "en": "This content was generated by AI.", "de": "Dieser Inhalt wurde mit KI erstellt.",
    "fr": "Ce contenu a été généré par une IA.", "es": "Este contenido fue generado por IA.",
    "ko": "이 콘텐츠는 AI가 생성했습니다.", "hi": "यह सामग्री एआई द्वारा बनाई गई है।",
}
APP_LEVEL = {
    NOTICE: "Show users a notice that they are interacting with AI before or at first use (UI change, not per file).",
    DETECTOR: "Offer a free public detection tool. Sigil's hosted verify page covers this; link it from your site.",
}


def _font(size: int, text: str):
    needs_cjk = any(ord(ch) > 0x2E80 for ch in text)
    patterns = (["/usr/share/fonts/**/NotoSansCJK*.tt*", "/usr/share/fonts/**/NotoSerifCJK*.tt*"]
                if needs_cjk else ["/usr/share/fonts/**/DejaVuSans-Bold.ttf", "/usr/share/fonts/**/DejaVuSans.ttf"])
    for pat in patterns:
        hits = glob.glob(pat, recursive=True)
        if hits:
            return ImageFont.truetype(hits[0], size)
    return ImageFont.load_default(size=size)


def add_visible_label(img: Image.Image, text: str) -> Image.Image:
    img = img.convert("RGBA")
    w, h = img.size
    size = max(12, int(min(w, h) * 0.035))
    font = _font(size, text)
    overlay = Image.new("RGBA", img.size, (0, 0, 0, 0))
    d = ImageDraw.Draw(overlay)
    tb = d.textbbox((0, 0), text, font=font)
    pad = size // 2
    bw, bh = tb[2] - tb[0] + pad * 2, tb[3] - tb[1] + pad * 2
    x, y = pad, h - bh - pad
    d.rounded_rectangle((x, y, x + bw, y + bh), radius=bh // 3, fill=(15, 15, 20, 190))
    d.text((x + pad - tb[0], y + pad - tb[1]), text, font=font, fill=(255, 255, 255, 245))
    return Image.alpha_composite(img, overlay)


@dataclass
class MarkOptions:
    provider: str
    system: str
    system_version: str = ""
    org: str = "default"
    jurisdictions: tuple[str, ...] = ("eu", "ca", "in", "kr")
    deepfake: bool = False
    monthly_users: int = 0
    visible_label: bool | None = None   # None = decide from the rules
    label_lang: str = "en"
    output_format: str | None = None    # PNG | JPEG | WEBP; default keeps input format
    composite: bool = False             # AI edit of a real photo vs fully generated


@dataclass
class Receipt:
    content_id: str
    modality: str
    controls_applied: list[str]
    rules: list[dict]
    still_required: dict[str, str] = field(default_factory=dict)
    verify_url: str | None = None
    ruleset: str = policy.RULESET_VERSION

    def to_dict(self):
        return self.__dict__.copy()


class Sigil:
    def __init__(self, data_dir: str | Path = "data", public_url: str = "http://localhost:8000"):
        self.data_dir = Path(data_dir)
        self.registry = Registry(self.data_dir / "sigil.db")
        self.accounts = Accounts(self.registry.db)
        self.cert_dir = self.data_dir / "certs"
        self.public_url = public_url.rstrip("/")

    # ---------- marking ----------
    def mark_image(self, data: bytes, opts: MarkOptions) -> tuple[bytes, Receipt]:
        img = Image.open(io.BytesIO(data))
        in_fmt = (img.format or "PNG").upper()
        fmt = (opts.output_format or in_fmt).upper()
        fmt = "JPEG" if fmt == "JPG" else fmt
        if fmt not in provenance.MIME:
            fmt = "PNG"
        img.load()
        ctx = policy.Context("image", tuple(opts.jurisdictions), opts.deepfake, opts.monthly_users)
        need = policy.required_controls(ctx)
        applied = []

        want_label = opts.visible_label if opts.visible_label is not None else VISIBLE in need
        if want_label:
            img = add_visible_label(img, LABELS.get(opts.label_lang, LABELS["en"]))
            applied.append(VISIBLE)

        cid = watermark.new_content_id()
        img = watermark.embed(img, cid, PUBLIC_KEY)
        applied += [WATERMARK, IDENTIFIER]

        buf = io.BytesIO()
        if fmt == "JPEG":
            img.convert("RGB").save(buf, "JPEG", quality=92)
        else:
            img.save(buf, fmt, **({"quality": 92} if fmt == "WEBP" else {}))

        cid_hex = watermark.id_to_hex(cid)
        created = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        disclosure = {
            "provider": opts.provider, "system": opts.system, "system_version": opts.system_version,
            "created": created, "content_id": cid_hex, "ai_generated": True,
            "watermark": watermark.SCHEME, "ruleset": policy.RULESET_VERSION,
            "jurisdictions": list(opts.jurisdictions), "verify": f"{self.public_url}/v/{cid_hex}",
        }
        out = provenance.sign(buf.getvalue(), fmt, disclosure, self.cert_dir, composite=opts.composite)
        applied.append(C2PA)

        self.registry.record(
            content_id=cid_hex, org=opts.org, modality="image", sha256=hashlib.sha256(out).hexdigest(),
            provider=opts.provider, system=opts.system, system_version=opts.system_version,
            created_at=created, jurisdictions=opts.jurisdictions, controls=applied,
            ruleset=policy.RULESET_VERSION)
        return out, self._receipt(cid_hex, "image", ctx, applied)

    def mark_text(self, text: str, opts: MarkOptions, disclose: bool | None = None) -> tuple[str, Receipt]:
        ctx = policy.Context("text", tuple(opts.jurisdictions), opts.deepfake, opts.monthly_users)
        applied = [IDENTIFIER, TEXT_MARK]
        cid_hex = watermark.id_to_hex(watermark.new_content_id())
        out = text
        if disclose:
            out = f"{text.rstrip()}\n\n{TEXT_DISCLOSURES.get(opts.label_lang, TEXT_DISCLOSURES['en'])}"
            applied.append(VISIBLE)
        created = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        self.registry.record(
            content_id=cid_hex, org=opts.org, modality="text",
            sha256=hashlib.sha256(text.strip().encode()).hexdigest(), provider=opts.provider,
            system=opts.system, system_version=opts.system_version, created_at=created,
            jurisdictions=opts.jurisdictions, controls=applied, ruleset=policy.RULESET_VERSION,
            fingerprint=text_fingerprint(text))
        r = self._receipt(cid_hex, "text", ctx, applied)
        r.still_required[TEXT_MARK + "_upstream"] = (
            "Text fingerprints are logged so Sigil can detect your output, but a statistical text "
            "watermark has to be applied at generation time. Turn on your model provider's text "
            "watermarking (OpenAI and Anthropic both offer it) for the robust layer.")
        return out, r

    def _receipt(self, cid, modality, ctx, applied) -> Receipt:
        rules = policy.applicable_rules(ctx)
        need = policy.required_controls(ctx)
        still = {c: APP_LEVEL.get(c, "Not applied to this item.") for c in need if c not in applied}
        if DETECTOR in still:
            still[DETECTOR] = APP_LEVEL[DETECTOR] + f" ({self.public_url}/verify)"
        return Receipt(cid, modality, applied,
                       [{"id": r.id, "law": r.law, "status": policy.rule_status(r)} for r in rules],
                       still, f"{self.public_url}/v/{cid}")

    # ---------- verification ----------
    def verify_image(self, data: bytes, ctx: policy.Context | None = None) -> dict:
        img = Image.open(io.BytesIO(data))
        fmt = (img.format or "").upper()
        img.load()
        c2 = provenance.read(data, fmt)
        wm = watermark.detect(img, PUBLIC_KEY)
        record = self.registry.get(wm["content_id"]) if wm["found"] else None
        record = record or self.registry.by_hash(hashlib.sha256(data).hexdigest())
        if not record and c2.get("sigil"):
            record = self.registry.get(c2["sigil"].get("content_id", ""))
        ai = bool(c2["ai_generated"] or wm["found"] or record)
        layers = {
            C2PA: "present" if c2["present"] else "missing",
            WATERMARK: "present" if wm["found"] else "not detected",
            IDENTIFIER: "present" if (wm["found"] or (c2.get("sigil") or {}).get("content_id")) else "missing",
            VISIBLE: "applied" if record and VISIBLE in (record.get("controls") or []) else "check manually",
        }
        report = {"ai_generated": ai, "verdict": self._verdict(ai, c2, wm), "c2pa": c2,
                  "watermark": wm, "record": record, "layers": layers}
        self.registry.audit(record["org"] if record else "public", "verify",
                            record["content_id"] if record else None, {"ai": ai})
        if ctx:
            report["compliance"] = self.compliance(ctx, layers)
        return report

    def verify_text(self, text: str, ctx: policy.Context | None = None) -> dict:
        record, score = self.registry.match_text(text)
        layers = {TEXT_MARK: "present" if record else "not found", IDENTIFIER: "present" if record else "missing"}
        report = {"ai_generated": bool(record), "match_score": round(score, 3), "record": record,
                  "verdict": ("Logged AI output from " + record["provider"]) if record else
                  "No Sigil record found. This does not prove a human wrote it.", "layers": layers}
        if ctx:
            report["compliance"] = self.compliance(ctx, layers)
        return report

    @staticmethod
    def _verdict(ai, c2, wm) -> str:
        if c2["present"] and c2["ai_generated"] and wm["found"]:
            return "AI-generated: signed provenance and watermark both present."
        if wm["found"]:
            return "AI-generated: watermark found (provenance metadata was stripped)."
        if c2["present"] and c2["ai_generated"]:
            return f"AI-generated per C2PA manifest from {c2.get('generator') or c2.get('issuer')}."
        if c2["present"]:
            return "Has a C2PA manifest but it does not declare AI generation."
        return "No AI marking found. Absence of a mark does not prove the content is authentic."

    @staticmethod
    def compliance(ctx: policy.Context, layers: dict) -> dict:
        need = policy.required_controls(ctx)
        items, ok = [], True
        for control, rule_ids in need.items():
            if control in APP_LEVEL:
                status = "app-level"
            else:
                status = layers.get(control, "missing")
            passed = status in ("present", "applied", "app-level")
            if status == "check manually":
                passed = None
            if passed is False:
                ok = False
            items.append({"control": control, "status": status, "required_by": rule_ids, "pass": passed,
                          "note": APP_LEVEL.get(control, "")})
        rules = [{"id": r.id, "law": r.law, "status": policy.rule_status(r), "penalty": r.penalty}
                 for r in policy.applicable_rules(ctx)]
        return {"ok": ok, "items": items, "rules": rules, "ruleset": policy.RULESET_VERSION,
                "disclaimer": "Engineering guidance, not legal advice."}
